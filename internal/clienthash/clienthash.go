// Package clienthash validates the values clients send in place of secrets.
package clienthash

// Valid reports whether s looks like a client-side hash: 64 hex characters.
func Valid(s string) bool {
	if len(s) != 64 {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if !(c >= '0' && c <= '9' || c >= 'a' && c <= 'f' || c >= 'A' && c <= 'F') {
			return false
		}
	}
	return true
}
